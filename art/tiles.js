// art/index.js merges these base grids with every day's (art/days/) and slices them here.
function stamp(rows, art, x, y) {
  const out = rows.slice();
  art.forEach((line, j) => {
    const row = [...out[y + j]];
    [...line].forEach((ch, i) => { if (ch !== '.') row[x + i] = ch; });
    out[y + j] = row.join('');
  });
  return out;
}

// Single tiles plus blocks cut into 16×16 tiles (identical cuts shared), in declaration order.
export function sliceTileset(singles, kinds, blockDefs) {
  const tiles = { ...singles };
  const tileKinds = { ...kinds };
  const blocks = {};
  const seen = new Map(Object.entries(singles).map(([name, rows]) => [rows.join('\n'), name]));
  for (const [name, def] of Object.entries(blockDefs)) {
    let rows = def.rows;
    if (rows.length !== def.h * tileSize || rows.some((row) => row.length !== def.w * tileSize)) {
      throw new Error(`block ${name}: art must be ${def.w * tileSize}×${def.h * tileSize}`);
    }
    for (const sign of def.signs ?? []) rows = stamp(rows, textGrid(sign.text, 't'), sign.x, sign.y);
    const cells = [];
    for (let ty = 0; ty < def.h; ty++) {
      const line = [];
      for (let tx = 0; tx < def.w; tx++) {
        const part = rows.slice(ty * tileSize, ty * tileSize + tileSize).map((row) => row.slice(tx * tileSize, tx * tileSize + tileSize));
        const key = part.join('\n');
        if (!/[^.\n]/.test(key)) { line.push(null); continue; }
        let tileName = seen.get(key);
        if (!tileName) {
          tileName = `${name}-${tx}-${ty}`;
          seen.set(key, tileName);
          tiles[tileName] = part;
          tileKinds[tileName] = def.kind;
        }
        line.push(tileName);
      }
      cells.push(line);
    }
    const solid = (def.solid ?? Array.from({ length: def.h }, () => '#'.repeat(def.w)))
      .map((row) => [...row].map((ch) => ch === '#'));
    blocks[name] = { w: def.w, h: def.h, kind: def.kind, solid, tiles: cells, rows };
  }
  return { tiles, tileKinds, blocks };
}

export function isSolidKind(kind) {
  return collideKinds.includes(kind);
}
