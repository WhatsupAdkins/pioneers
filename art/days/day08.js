// The Mercantile's front with another roof: slate grey, or weathered green.
const roofs = {
  rust: (rows) => rows,
  slate: (rows) => rows.map((row, y) => (y < 12 ? row.replace(/u/g, 'l').replace(/b/g, 'L') : row)),
  green: (rows) => rows.map((row, y) => (y < 12 ? row.replace(/u/g, 'e').replace(/b/g, 'E') : row)),
};
const storefront = (text, roof) => {
  const sign = blockArt.mercantile.signs[0];
  const x = Math.max(2, Math.round((64 - (text.length * 6 - 1)) / 2));
  return { w: 4, h: 4, kind: 'building', signs: [{ text, x, y: sign.y }], rows: roofs[roof](blockArt.mercantile.rows) };
};

