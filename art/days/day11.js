// The right-facing frames are the left-facing ones read backwards.
const mirror = (rows) => rows.map((row) => [...row].reverse().join(''));
// Step frames: the standing frame with its last four rows (legs and feet) swapped.
const withLegs = (rows, legs) => [...rows.slice(0, rows.length - legs.length), ...legs];

